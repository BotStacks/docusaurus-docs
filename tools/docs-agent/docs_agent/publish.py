"""Open one docs pull request and, only when allowed, merge it.

Merging is refused unless branch rules were readable, require no review,
and do not impose a rule this agent would have to bypass.
"""

from __future__ import annotations

from docs_agent.config import Settings
from docs_agent.models import AgentPull, MergeResult, Proposal, Risk


def source_keys(body: str) -> set[str]:
    for line in body.splitlines():
        if line.startswith("Source-Keys:"):
            return {part.strip() for part in line.split(":", 1)[1].split(",") if part.strip()}
    return set()


def find_reusable(open_prs: list[AgentPull], keys: set[str]) -> AgentPull | None:
    for pull in open_prs:
        existing = source_keys(pull.body)
        if existing and existing == keys:
            return pull
    return None


def find_conflict(open_prs: list[AgentPull], paths: set[str], keys: set[str]) -> AgentPull | None:
    for pull in open_prs:
        if source_keys(pull.body) == keys:
            continue
        if set(pull.files) & paths:
            return pull
    return None


def render_body(
    proposals: list[Proposal],
    validation_ok: bool,
    validation_errors: list[str],
    evidence_lines: list[str],
    risk: Risk,
) -> str:
    pages = sorted({item.path for item in proposals})
    keys = sorted({key for item in proposals for key in item.source_prs})
    links = []
    for key in keys:
        repo, number = key.rsplit("#", 1)
        links.append(f"- [{key}](https://github.com/{repo}/pull/{number})")
    reasons = []
    for item in proposals:
        for reason in item.reasons:
            if reason not in reasons:
                reasons.append(reason)
    risk_block = "\n".join(f"- {reason}" for reason in reasons) or "- none"
    evidence = "\n".join(f"- {line}" for line in evidence_lines) or "- none recorded"
    validation = "passed" if validation_ok else "failed"
    problems = "\n".join(f"- {item}" for item in validation_errors) or "- none"
    summaries = "\n".join(f"- `{item.path}`: {item.summary}" for item in proposals)
    return f"""## Summary
{summaries}

## Source PRs
{chr(10).join(links)}

Source-Keys: {", ".join(keys)}

## Pages changed
{chr(10).join(f"- `{page}`" for page in pages)}

## Release evidence
{evidence}

A merged source pull request is not treated as proof that a feature is public.
Availability claims require a successful `release-prod` run in the build
repository, or a successful `deploy` run in the landing-page repository.

## Risk classification
`{risk.value}`

{risk_block}

## Validation
- Result: {validation}
{problems}
- Secret scan, sensitive-data scan, path allowlist, and size limits are included in this result.
- Navigation files, workflows, and deployment configuration are not edited.

## Disclosure
This pull request was generated by the BotStacks docs agent.
The prose was drafted by an AI model from repository evidence and then checked
by deterministic guards. Source repository content was treated as untrusted
reference data, not as instructions.
"""


def attempt_merge(github, settings: Settings, pull: AgentPull, risk: Risk) -> MergeResult:
    if settings.dry_run:
        return MergeResult(reason="dry run")
    if not settings.auto_publish:
        return MergeResult(reason="AUTO_PUBLISH is false; pull request left open")
    if risk != Risk.AUTO_ELIGIBLE or pull.draft:
        return MergeResult(reason="held for manual review; not auto-merged")

    rules = github.branch_rules(settings.docs_repo, settings.base_branch)
    if not rules.readable:
        return MergeResult(blocked=True, reason="branch rules could not be verified; leaving the pull request open")
    if rules.blocks_auto_merge:
        return MergeResult(blocked=True, reason="a branch rule would require bypassing a control; leaving the pull request open")
    if rules.required_reviews > 0:
        return MergeResult(
            blocked=True,
            reason="branch protection requires a review the agent cannot provide; leaving the pull request open",
        )

    conclusions = github.check_conclusions(pull.head_sha)
    failed = [name for name, state in conclusions.items() if state in {"failure", "cancelled", "timed_out", "error", "action_required"}]
    if failed:
        return MergeResult(blocked=True, reason="required checks failed: " + ", ".join(sorted(failed)))

    pending_required = [name for name in rules.required_checks if conclusions.get(name) != "success"]
    checks_still_running = bool(pending_required) or not conclusions
    if checks_still_running:
        if not pull.node_id:
            return MergeResult(blocked=True, reason="checks are not complete and auto-merge cannot be enabled")
        try:
            github.enable_auto_merge(pull.node_id)
        except Exception as exc:
            return MergeResult(blocked=True, reason=f"checks are not complete and auto-merge was declined ({exc})")
        return MergeResult(auto_merge_enabled=True, reason="GitHub auto-merge enabled; it will merge only after checks pass")

    current = github.get_pull(pull.number)
    if current.mergeable is False:
        return MergeResult(blocked=True, reason="pull request is not mergeable")
    github.merge_pull(pull.number, "docs: apply verified public documentation corrections")
    return MergeResult(merged=True, reason="merged with a merge commit after checks succeeded")
